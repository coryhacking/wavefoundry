_AGENT_ROLE_LINE_RE = re.compile(r"^Role:\s+", re.MULTILINE)
_AGENT_CATEGORY_LINE_RE = re.compile(r"^Category:\s+", re.MULTILINE)


def _ensure_agent_frontmatter(content: str, destination: str) -> str:
    """Inject the `Role:`/`Category:` frontmatter a fresh ``docs/agents/**`` carrier needs.

    The agent-metadata docs-lint validator requires every ``docs/agents/**/*.md`` to
    declare ``Role:`` (equal to the filename slug) and ``Category:`` (path-derived). A
    carrier materialized fresh from a seed body that omits those lines would fail the
    pack's own validator (the failure that blocked a 1.13.0 upgrade at the docs gate),
    so inject the missing field(s) here — **only when absent**, never overwriting a
    value the seed or an existing project-authored file already provides. Category is
    derived from the validator's own ``_expected_agent_category`` so the two never
    drift; a destination the validator exempts (category ``None``) gets nothing.
    Destinations the validator does not govern (e.g. ``docs/prompts/**``) are returned
    unchanged. Applied on the fresh-carrier path only, so the update path is untouched.
    """

    if not (destination.startswith("docs/agents/") and destination.endswith(".md")):
        return content
    # Local import: defer the wave_lint_lib edge to call time so module load stays
    # decoupled across the setup/upgrade/hook subprocess contexts that run rendering.
    from wave_lint_lib.wave_validators import _expected_agent_category

    dest = Path(destination)
    category = _expected_agent_category(dest)
    if category is None:
        return content
    needed: list[str] = []
    if not _AGENT_ROLE_LINE_RE.search(content):
        needed.append(f"Role: {dest.stem}")
    if not _AGENT_CATEGORY_LINE_RE.search(content):
        needed.append(f"Category: {category}")
    if not needed:
        return content
    block = "\n".join(needed)
    status_match = re.search(r"^Status:.*$", content, re.MULTILINE)
    if status_match:
        idx = status_match.end()
        return content[:idx] + "\n" + block + content[idx:]
    heading_match = re.search(r"^#\s.*$", content, re.MULTILINE)
    if heading_match:
        idx = heading_match.end()
        return content[:idx] + "\n\n" + block + content[idx:]
    return block + "\n\n" + content


def _contained_review_carrier_path(repo_root: Path, destination: str) -> Path:
    """Resolve one registered carrier and refuse writes outside ``repo_root``.

    Carrier destinations are fixed by the typed registry, but an existing
    repository can place a symlink at the destination or in one of its parent
    directories.  Setup, upgrade, and direct rendering must not follow that
    repository-controlled path into a sibling directory.  Returning the
    resolved path also prevents a later open from re-following the symlink
    chain that was checked here.
    """

    root = repo_root.resolve()
    candidate = repo_root / destination
    try:
        resolved = candidate.resolve(strict=False)
    except OSError as exc:
        raise RuntimeError(
            f"review carrier path cannot be resolved safely: {destination}: {exc}"
        ) from exc
    if not resolved.is_relative_to(root):
        raise RuntimeError(
            "review carrier path escapes the repository root through a symlink: "
            f"{destination}"
        )
    return resolved


def _write_review_carrier_text(path: Path, content: str) -> None:
    """Write a checked carrier without following a raced final symlink."""

    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    try:
        fd = os.open(path, flags, 0o666)
    except OSError as exc:
        raise RuntimeError(f"review carrier write refused for {path}: {exc}") from exc
    with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
        handle.write(content)


