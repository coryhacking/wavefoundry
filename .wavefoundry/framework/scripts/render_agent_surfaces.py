def render_agent_surfaces(repo_root: Path) -> list[str]:
    """Render auto-Guru tier 2–3 surfaces. Returns paths written or updated."""
    # Wave 1skt1: this must run before the historical Guru-availability early
    # return so setup/upgrade/render can repair review carriers in repositories
    # that intentionally do not expose Guru.
    preflight_agent_surface_paths(repo_root)
    # Wave 1p6lp: the skill registry renders BEFORE the reconcile passes so a
    # freshly migrated carrier skill (wf-guru on Codex) is reconciled in the
    # same render, and BEFORE the Guru gate because lifecycle skills are not
    # Guru-gated (per-skill gates live in the registry).
    skills_written = render_skills(repo_root)
    lifecycle_written = reconcile_lifecycle_prompt_baselines(repo_root)
    scaffold_written = reconcile_scaffold_baselines(repo_root)
    # The phase-0c in-process reconciler can still be old code on the upgrade
    # that installs this release. Replay only its shared upgrade-policy marker
    # from the extracted renderer so this one surface converges in that run.
    try:
        upgrade_policy_written = list(reconcile_upgrade_policy_surface(repo_root))
    except ValueError as exc:
        raise RuntimeError(str(exc)) from exc
    review_written = reconcile_review_protocol_surfaces(repo_root)
    # Policy companions include optional carriers materialized by the review
    # protocol pass (for example the agent and council review prompts). Run
    # policy second so one render converges from a sparse pre-adoption tree.
    policy_written = reconcile_review_policy_surfaces(repo_root)
    context_written = reconcile_context_efficiency_surface(repo_root)
    framework_written = list(
        dict.fromkeys(
            [
                *skills_written,
                *lifecycle_written,
                *scaffold_written,
                *upgrade_policy_written,
                *review_written,
                *policy_written,
                *context_written,
            ]
        )
    )
    if not guru_available(repo_root):
        return framework_written

    # Preflight every path this Guru-enabled pass may write before the first
    # native/thin-pointer mutation.  The initial carrier census intentionally
    # ignores a missing native wrapper, so a symlinked wrapper directory with
    # no leaf file would otherwise escape during materialization and be noticed
    # only by the second carrier reconciliation.
    preflight_agent_surface_paths(repo_root)

    written: list[str] = list(framework_written)

    # Wave 1t72b (1t729 live find): tier-3 templates are written unconditionally
    # and then RECONCILED by the closing carrier pass, so write-time comparison
    # oscillates (template != reconciled bytes every render). "Written" for the
    # manifest means NET change across the whole render: snapshot pre-render
    # bytes here, decide after the closing reconcile pass below.
    tier3_candidates: list[Path] = []
    tier3_pre_bytes: dict[Path, "bytes | None"] = {}

    def _tier3_write(path: Path, content: str) -> None:
        try:
            tier3_pre_bytes[path] = path.read_bytes() if path.exists() else None
        except OSError:
            tier3_pre_bytes[path] = None
        tier3_candidates.append(path)
        write_text(path, content)

    # Tier 3 — optional native surfaces
    if (repo_root / ".cursor").exists():
        cursor_rule = repo_root / ".cursor" / "rules" / "auto-guru.mdc"
        _tier3_write(cursor_rule, CURSOR_AUTO_GURU_MDC)

    if (repo_root / ".claude").exists():
        claude_agent = repo_root / ".claude" / "agents" / "guru.md"
        _tier3_write(claude_agent, CLAUDE_GURU_AGENT)

    # Wave 1p6lp: the Codex guru skill is registry-rendered (wf-guru) by
    # render_skills above; the ad-hoc CODEX_AUTO_GURU_SKILL write is retired.

    # Root @import bridge — make CLAUDE.md a real @AGENTS.md import (1p5xc).
    # The single, contained @import; replaces the prose "read AGENTS.md first"
    # pointer so AGENTS.md is the deterministic single source of truth.
    if patch_root_bridge(repo_root / "CLAUDE.md"):
        written.append("CLAUDE.md")

    # Tier 2 — thin pointers (marker blocks)
    claude_path = repo_root / "CLAUDE.md"
    if claude_path.is_file():
        claude_body = CLAUDE_AUTO_GURU_SECTION.strip()
        claude_block = f"{MARKER_BEGIN}\n{claude_body}\n{MARKER_END}"
        text = strip_legacy_auto_guru_lines(claude_path.read_text(encoding="utf-8"))
        if MARKER_BEGIN in text:
            text = re.sub(
                re.escape(MARKER_BEGIN) + r".*?" + re.escape(MARKER_END),
                claude_block,
                text,
                count=1,
                flags=re.DOTALL,
            )
        else:
            # Replace legacy hand-authored section if present
            legacy = re.compile(
                r"\n## Code and documentation questions \(auto-Guru\)\n.*?(?=\n## |\Z)",
                re.DOTALL,
            )
            if legacy.search(text):
                text = legacy.sub("\n" + claude_block + "\n", text, count=1)
            else:
                text = insert_after_heading(text, "## Startup Order", claude_block)
        if text != claude_path.read_text(encoding="utf-8"):
            claude_path.write_text(text, encoding="utf-8")
            written.append("CLAUDE.md")

    pointer_specs: list[tuple[Path, str]] = [
        (repo_root / ".junie" / "guidelines.md", "## Key Rules"),
        (repo_root / "WARP.md", "## Key Rules"),
        (repo_root / ".github" / "copilot-instructions.md", "## Key Guardrails"),
    ]
    for path, heading in pointer_specs:
        if patch_thin_pointer(path, AUTO_GURU_BULLET, after_heading=heading):
            written.append(path.relative_to(repo_root).as_posix())  # Wave 1p6dx: forward-slash

    cursor_ctx = repo_root / ".cursor" / "rules" / "project-context.mdc"
    if cursor_ctx.is_file():
        text = strip_legacy_auto_guru_section(
            strip_legacy_auto_guru_lines(cursor_ctx.read_text(encoding="utf-8"))
        )
        updated = upsert_marked_region(text, CURSOR_PROJECT_CONTEXT_BLOCK.strip())
        if updated != cursor_ctx.read_text(encoding="utf-8"):
            cursor_ctx.write_text(updated, encoding="utf-8")
            written.append(cursor_ctx.relative_to(repo_root).as_posix())  # Wave 1p6dx: forward-slash

    # Native Guru wrappers are materialized above, after the initial carrier
    # census. Reconcile again so the first public render gives them the same
    # protocol minimum and later renders cannot overwrite it away.
    reconciled_again = reconcile_review_protocol_surfaces(repo_root)

    # Net-change decision for the tier-3 candidates: a file whose final
    # post-reconcile bytes equal its pre-render bytes was not written in any
    # sense the manifest should report.
    for path in tier3_candidates:
        try:
            post = path.read_bytes() if path.exists() else None
        except OSError:
            continue
        if post != tier3_pre_bytes.get(path):
            written.append(path.relative_to(repo_root).as_posix())  # Wave 1p6dx: forward-slash

    # The closing reconcile pass legitimately rewrites tier-3 templates back to
    # their reconciled form every render; those paths' NET verdict was already
    # decided above, so only non-candidate carriers merge from its return.
    tier3_rels = {
        path.relative_to(repo_root).as_posix() for path in tier3_candidates
    }
    for rel in reconciled_again:
        if rel not in written and rel not in tier3_rels:
            written.append(rel)

    # Dedupe while preserving order (CLAUDE.md may be touched by both the
    # root-bridge step and the auto-Guru tier-2 step).
    deduped: list[str] = []
    for rel in written:
        if rel not in deduped:
            deduped.append(rel)
    return deduped


def main() -> int:
    import argparse
    import sys

    from render_platform_surfaces import discover_repo_root

    parser = argparse.ArgumentParser(description="Render auto-Guru agent routing surfaces.")
    parser.add_argument("--repo-root", default="", help="Repository root (default: auto-discover).")
    args = parser.parse_args()
    repo_root = Path(args.repo_root).resolve() if args.repo_root else discover_repo_root()
    try:
        paths = render_agent_surfaces(repo_root)
    except RuntimeError as exc:
        print(f"render_agent_surfaces: ERROR — {exc}", file=sys.stderr)
        return 1
    if not paths:
        if not guru_available(repo_root):
            print(f"skip: {GURU_ROLE_REL} not found", file=sys.stderr)
        return 0
    for rel in paths:
        print(rel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
