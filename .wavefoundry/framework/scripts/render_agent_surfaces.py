def upsert_marked_region(text: str, region: str) -> str:
    text = _canonicalize_owned_markers(text)
    block = f"{MARKER_BEGIN}\n{region.rstrip()}\n{MARKER_END}"
    pattern = re.compile(
        re.escape(MARKER_BEGIN) + r".*?" + re.escape(MARKER_END),
        re.DOTALL,
    )
    if pattern.search(text):
        return pattern.sub(block, text, count=1)
    return text.rstrip() + "\n\n" + block + "\n"


def insert_after_heading(text: str, heading: str, inner: str) -> str:
    """Insert marked block after the first line matching ``heading`` (markdown ## title)."""
    if MARKER_BEGIN in text:
        return upsert_marked_region(text, inner)
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.strip() == heading:
            insert_at = index + 1
            while insert_at < len(lines) and lines[insert_at].strip() == "":
                insert_at += 1
            marked = f"{MARKER_BEGIN}\n{inner}\n{MARKER_END}"
            new_lines = lines[:insert_at] + ["\n", marked, "\n"] + lines[insert_at:]
            return "".join(new_lines)
    marked = f"{MARKER_BEGIN}\n{inner}\n{MARKER_END}"
    return text.rstrip() + "\n\n" + marked + "\n"


def strip_legacy_auto_guru_section(text: str) -> str:
    """Remove unmarked ``## Code and documentation questions (auto-Guru)`` sections."""
    pattern = re.compile(
        rf"\n## Code and documentation questions \(auto-Guru\)\n.*?(?=\n## |\n<!-- {marker_namespaces.MARKER_NAMESPACE_ALTERNATION}:|\Z)",
        re.DOTALL,
    )
    return pattern.sub("\n", text)


def strip_legacy_auto_guru_lines(text: str) -> str:
    """Remove hand-seeded auto-Guru bullets superseded by marker blocks."""
    text = _canonicalize_owned_markers(text)
    pattern = re.compile(
        r"^\- Code and documentation Q&A:.*\n",
        re.MULTILINE,
    )
    if MARKER_BEGIN in text:
        parts = []
        in_marker = False
        for line in text.splitlines(keepends=True):
            if MARKER_BEGIN in line:
                in_marker = True
                parts.append(line)
                continue
            if MARKER_END in line:
                in_marker = False
                parts.append(line)
                continue
            if in_marker:
                parts.append(line)
                continue
            if line.strip().startswith("- Code and documentation Q&A:"):
                continue
            parts.append(line)
        return "".join(parts)
    return pattern.sub("", text)


def patch_thin_pointer(
    path: Path,
    inner: str,
    *,
    after_heading: str | None = None,
    root: Path,
) -> bool:
    if not path.is_file():
        return False
    disk_text = _read_repo_text(root, path)
    original = strip_legacy_auto_guru_section(
        strip_legacy_auto_guru_lines(_canonicalize_owned_markers(disk_text))
    )
    if after_heading:
        updated = insert_after_heading(original, after_heading, inner)
    else:
        updated = upsert_marked_region(original, inner)
    if updated != disk_text:
        _write_repo_text_platform_newlines(root, path, updated)
        return True
    return False


def patch_root_bridge(path: Path, *, root: Path) -> bool:
    """Ensure the root CLAUDE.md is a real ``@AGENTS.md`` import (1p5xc).

    Replaces the legacy prose pointer ("Thin pointer. Read `AGENTS.md` first…")
    with a marked ``@AGENTS.md`` import block so Claude loads AGENTS.md
    deterministically. Idempotent. This is the only ``@import`` the framework
    adopts and only at the root — never per-folder.
    """
    if not path.is_file():
        return False
    original = _read_repo_text(root, path)
    text = _canonicalize_owned_markers(original)

    # Refresh an existing bridge block in place.
    bridge_re = re.compile(
        re.escape(ROOT_BRIDGE_MARKER_BEGIN) + r".*?" + re.escape(ROOT_BRIDGE_MARKER_END),
        re.DOTALL,
    )
    if bridge_re.search(text):
        text = bridge_re.sub(ROOT_BRIDGE_BLOCK, text, count=1)
        if text != original:
            _write_repo_text_platform_newlines(root, path, text)
            return True
        return False

    # Replace the legacy prose pointer if present; otherwise insert after the H1.
    if _LEGACY_THIN_POINTER_RE.search(text):
        text = _LEGACY_THIN_POINTER_RE.sub(ROOT_BRIDGE_BLOCK + "\n", text, count=1)
    else:
        lines = text.splitlines(keepends=True)
        insert_at = 0
        for index, line in enumerate(lines):
            if line.startswith("# "):
                insert_at = index + 1
                while insert_at < len(lines) and lines[insert_at].strip() == "":
                    insert_at += 1
                break
        block = ROOT_BRIDGE_BLOCK + "\n"
        new_lines = lines[:insert_at] + ["\n", block, "\n"] + lines[insert_at:]
        text = "".join(new_lines)

    if text != original:
        _write_repo_text_platform_newlines(root, path, text)
        return True
    return False


def write_text(path: Path, content: str, *, root: Path) -> bool:
    """Write ``content`` and report whether the on-disk bytes changed.

    Wave 1t72b (1t727-adjacent live find): callers report written paths into
    the sync manifest, so a byte-identical rewrite must return False — the
    same changed-only semantics as this module's marker-block writers. Wave
    200ey (change 1zyv2): the contained write rooted at ``root``.
    """
    # Encoded verbatim, no newline translation, so the embedded line terminators are
    # byte-identical on every rendering host (mirrors render_platform_surfaces.write_text,
    # wave 1p7tz): a re-render on native Windows must not turn the generated agent
    # surfaces (auto-guru.mdc, guru.md, SKILL.md) into CRLF.
    return _write_repo_bytes(root, path, content.encode("utf-8"))


