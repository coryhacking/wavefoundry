# Wave 1zyb3 (change 1zxnu): the first body line of every SKILL.md rendered
# for a declared skill. It marks the file as renderer-owned, so a render never
# overwrites a hand-written SKILL.md and removes the marked folder of a skill
# the distribution stops declaring. Framework (wf-) skills stay unmarked.
DECLARED_SKILL_MARKER = "<!-- wavefoundry:declared-skill -->"


def skill_document(skill: Skill) -> str:
    """Assemble the standard SKILL.md text for one registry entry."""

    body = f"{DECLARED_SKILL_MARKER}\n\n{skill.body}" if skill.declared else skill.body
    return (
        f"---\nname: {skill.name}\ndescription: {skill.description}\n---\n\n{body}"
    )


def _legacy_declared_skill_document(skill: Skill) -> str:
    """The pre-marker rendering of a declared skill (wave 1zv8c), adopted as owned."""

    return skill_document(_dataclass_replace(skill, declared=False))


def has_declared_skill_marker(text: str) -> bool:
    """Whether ``text`` carries the declared-skill marker as its first body line.

    The marker must be the first non-blank line after a frontmatter block that
    opens on the first line; a trailing carriage return is ignored. A plain
    line scan, not a YAML parser.
    """

    lines = [line[:-1] if line.endswith("\r") else line for line in text.split("\n")]
    if not lines or lines[0] != "---":
        return False
    for index in range(1, len(lines)):
        if lines[index] == "---":
            break
    else:
        return False
    for line in lines[index + 1:]:
        if line.strip():
            return line == DECLARED_SKILL_MARKER
    return False


def declared_skill_problems(skills: object = None) -> list[str]:
    """Every problem with the distribution's skill declaration (wave 1zv8c,
    change 1zv89): ``mcp_tool_extensions.skill_declaration_problems`` plus a
    name whose rendered path is one of ``STALE_SKILL_PATHS``, which this
    renderer owns. ``EXTENSION_SKILLS`` is read now when ``skills`` is None."""

    if skills is None:
        skills = getattr(mcp_tool_extensions, "EXTENSION_SKILLS", {})
    if not skills:
        return []
    problems = list(mcp_tool_extensions.skill_declaration_problems(skills))
    if isinstance(skills, Mapping):
        for name in skills:
            if not isinstance(name, str):
                continue
            for _host_root, skills_dir in SKILL_HOSTS:
                folder = f"{skills_dir}/{name}"
                if any(rel == folder or rel.startswith(f"{folder}/") for rel in stale_skill_paths()):
                    problems.append(
                        f"skill {name!r}: the name renders to the retired skill path {folder}, "
                        "which every render removes"
                    )
                    break
    return problems


def declared_skills() -> "tuple[Skill, ...]":
    """The distribution's declared skills as registry entries, read from
    ``mcp_tool_extensions.EXTENSION_SKILLS`` at call time (never a
    from-import, so a test base declaration and the upgrade old-code window
    see the current module). Raises ``RuntimeError`` naming every problem.
    Each renders a thin-pointer body labelled "skill", gated on its prompt doc.
    """

    skills = getattr(mcp_tool_extensions, "EXTENSION_SKILLS", {})
    if not skills:
        return ()
    problems = declared_skill_problems(skills)
    if problems:
        raise RuntimeError(
            "invalid EXTENSION_SKILLS declaration in mcp_tool_extensions; nothing was rendered: "
            + "; ".join(problems)
        )
    return tuple(
        Skill(
            name=name,
            description=spec["description"],
            body=_thin_pointer_body(
                spec["title"], spec["prompt_doc"], tuple(spec["summary"]), label="skill"
            ),
            requires_doc=spec["prompt_doc"],
            declared=True,
            prompt_doc_template=spec.get("prompt_doc_template"),
        )
        for name, spec in skills.items()
    )


def _declared_prompt_doc_creations(repo_root: Path) -> "dict[str, Path]":
    """``{prompt_doc: template}`` for every declared skill whose prompt doc is
    absent and whose declaration names a ``prompt_doc_template`` (wave 1zyb3,
    change 1zxnu). Resolves each template target first, then packaged, and
    raises naming the template path when neither exists, before any write."""

    creations: "dict[str, Path]" = {}
    for skill in declared_skills():
        template_name = skill.prompt_doc_template
        if not template_name or not skill.requires_doc:
            continue
        # ``lexists``: a dangling link at the prompt doc counts as present,
        # so the creation never writes through it (wave 1zyb3 delivery repair).
        if os.path.lexists(repo_root / skill.requires_doc) or skill.requires_doc in creations:
            continue
        try:
            creations[skill.requires_doc] = _resolve_install_asset(repo_root, template_name)
        except RuntimeError as exc:
            # Wave 200ey (200eu): the wrapped error is not echoed; the asset's
            # two locations are named as labels, never as absolute paths.
            raise RuntimeError(
                f"declared skill {skill.name!r}: missing prompt_doc_template "
                f"{_display_name(template_name)}: neither "
                f"{_install_asset_rel(template_name)} nor the packaged fallback "
                f"install/{_display_name(template_name)} exists; nothing was rendered"
            ) from exc
    return creations


def _skill_is_eligible(repo_root: Path, skill: Skill, creations: "Mapping[str, Path]") -> bool:
    """A skill renders where its gate doc exists or this render creates it."""

    return (
        not skill.requires_doc
        or skill.requires_doc in creations
        or (repo_root / skill.requires_doc).is_file()
    )


def _all_skills() -> "tuple[Skill, ...]":
    """The framework registry followed by the declared skills."""

    return (*SKILL_REGISTRY, *declared_skills())


def _skill_output_destinations(repo_root: Path) -> list[str]:
    """Every skill path the registry pass may write, honoring both gates.

    Validates the declared skills first, so ``preflight_agent_surface_paths``
    refuses an invalid declaration before any render writes (wave 1zv8c).
    """

    destinations: list[str] = []
    skills = _all_skills()
    creations = _declared_prompt_doc_creations(repo_root)
    for skill in skills:
        if not _skill_is_eligible(repo_root, skill, creations):
            continue
        for host_root, skills_dir in SKILL_HOSTS:
            if (repo_root / host_root).is_dir():
                destinations.append(f"{skills_dir}/{skill.name}/SKILL.md")
    return destinations


def _skill_path_has_symlink_component(root: Path, path: Path) -> bool:
    """Return whether any lexical component below ``root`` is a symlink."""

    try:
        relative = path.relative_to(root)
    except ValueError:
        return True
    current = root
    for part in relative.parts:
        current /= part
        if current.is_symlink():
            return True
    return False


def _refused_declared_skill_paths(
    root: Path,
    skills: "tuple[Skill, ...]",
    creations: "Mapping[str, Path]",
    active_skill_roots: "Mapping[str, Path]",
) -> "list[str]":
    """Repository-relative SKILL.md paths of eligible declared skills that a
    render must not overwrite (wave 1zyb3, change 1zxnu): an existing file
    without the marker whose bytes, ignoring CRLF, differ from the pre-marker
    rendering of the same skill. A marked or adoptable file is owned."""

    refused: list[str] = []
    for skill in skills:
        if not skill.declared or not _skill_is_eligible(root, skill, creations):
            continue
        legacy = _legacy_declared_skill_document(skill).encode("utf-8")
        for skills_dir, declared_root in active_skill_roots.items():
            target = declared_root / skill.name / "SKILL.md"
            if not target.is_file():
                continue
            try:
                existing = _read_repo_bytes(root, target)
            except OSError as exc:
                raise RuntimeError(
                    "cannot read the existing skill "
                    f"{_display_name(f'{skills_dir}/{skill.name}/SKILL.md')} ({_failure_class(exc)})"
                ) from None
            if has_declared_skill_marker(existing.decode("utf-8", errors="replace")):
                continue
            if existing.replace(b"\r\n", b"\n") == legacy:
                continue
            refused.append(f"{skills_dir}/{skill.name}/SKILL.md")
    return refused


def _is_link_or_reparse(path: Path, info: os.stat_result) -> bool:
    """Whether ``path`` is a symlink, a Windows junction or other reparse
    point, or resolves anywhere but its own lexical path."""

    if stat.S_ISLNK(info.st_mode):
        return True
    reparse = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0)
    if reparse and getattr(info, "st_file_attributes", 0) & reparse:
        return True
    try:
        return path.resolve(strict=False) != path
    except OSError:
        return True


class _SkillOrphan(NamedTuple):
    """One judged undeclared skill folder (wave 1zyb3; identities wave 200ey,
    change 200eu): the ``lstat`` identities ``(st_dev, st_ino)`` of the folder
    and its ``SKILL.md`` at the decision, which the removal re-checks."""

    rel: str
    skill_file: Path
    folder: Path
    folder_id: "tuple[int, int]"
    file_id: "tuple[int, int]"


def _identity(info: os.stat_result) -> "tuple[int, int]":
    return (info.st_dev, info.st_ino)


def _declared_skill_orphans(active_skill_roots: "Mapping[str, Path]") -> "list[_SkillOrphan]":
    """A :class:`_SkillOrphan` for every marked skill folder on an active
    host whose name no declared skill uses (wave 1zyb3, change 1zxnu).

    ``wf-`` folders are the framework's. A linked child (symlink, junction or
    reparse point, or one that resolves elsewhere) is skipped without reading
    through it, as is one whose SKILL.md is linked or not a regular file. A
    marked folder holding anything besides SKILL.md is left untouched and
    reported. Names compare casefolded, so a folder that differs from a
    declared name only in case is kept on every filesystem. Each root is
    already resolved and link-free, so a child's lexical path is its real one.
    The folder's and SKILL.md's ``lstat`` identities are recorded, and the
    marker is read through the contained read, whose descriptor must be the
    file judged (wave 200ey, change 200eu).
    """

    declared = {
        str(name).casefold() for name in getattr(mcp_tool_extensions, "EXTENSION_SKILLS", {}) or {}
    }
    orphans: list[_SkillOrphan] = []
    for skills_dir, declared_root in active_skill_roots.items():
        try:
            children = sorted(declared_root.iterdir(), key=lambda child: child.name)
        except FileNotFoundError:
            continue
        except OSError as exc:
            raise RuntimeError(
                f"cannot list the host skill root {_display_name(skills_dir)} ({type(exc).__name__})"
            ) from exc
        for child in children:
            if child.name.startswith("wf-") or child.name.casefold() in declared:
                continue
            try:
                child_info = os.lstat(child)
            except OSError:
                continue
            if _is_link_or_reparse(child, child_info) or not stat.S_ISDIR(child_info.st_mode):
                continue
            skill_file = child / "SKILL.md"
            try:
                file_info = os.lstat(skill_file)
            except OSError:
                continue
            if _is_link_or_reparse(skill_file, file_info) or not stat.S_ISREG(file_info.st_mode):
                continue
            try:
                # Each skill root is resolved and link-free, so the root is its
                # own containment boundary here.
                data, opened = contained_files.read_contained(
                    declared_root, skill_file, max_bytes=contained_files.DEFAULT_MAX_BYTES
                )
            except OSError:
                continue
            if _identity(opened) != _identity(file_info):
                continue
            if not has_declared_skill_marker(data.decode("utf-8", errors="replace")):
                continue
            rel = f"{skills_dir}/{child.name}/SKILL.md"
            try:
                entries = sorted(entry.name for entry in child.iterdir())
            except OSError:
                continue
            if entries != ["SKILL.md"]:
                print(
                    "render_agent_surfaces: NOTICE - undeclared skill folder left in place: "
                    f"{_display_name(f'{skills_dir}/{child.name}')} holds files besides its marked SKILL.md; "
                    "remove the folder by hand if it is no longer wanted",
                    file=sys.stderr,
                )
                continue
            orphans.append(
                _SkillOrphan(rel, skill_file, child, _identity(child_info), _identity(file_info))
            )
    return orphans


# ---------------------------------------------------------------------------
# Removal of judged entries (wave 200ey, change 200eu)
#
# A removal acts only on the entry that was judged: its identity
# ``(st_dev, st_ino)`` is recorded at the decision and re-checked right before
# the removal. Where ``dir_fd`` is supported (Linux, macOS, WSL2) the parent is
# opened with ``contained_files.open_contained_dir`` (an ``O_NOFOLLOW`` walk),
# the entry is checked with ``os.stat(..., dir_fd=..., follow_symlinks=False)``
# and removed relative to that descriptor, so the window narrows to an entry
# swapped inside the verified, descriptor-held directory, which is removed as
# a directory entry and never followed. Windows has no ``dir_fd``: the same
# re-check runs by path immediately before each removal, and a junction or
# link swapped in between is the documented remaining window.
# ---------------------------------------------------------------------------

_CAUSE_ENTRY_CHANGED = "the entry changed after it was judged"


def _descriptor_removal() -> bool:
    """Whether removals run relative to a directory descriptor."""
    return contained_files._dir_fd_supported() and os.rmdir in os.supports_dir_fd


def _remove_judged_entry(
    root: Path,
    parent_parts: "tuple[str, ...]",
    name: str,
    identity: "tuple[int, int]",
    *,
    directory: bool,
    parent_identity: "tuple[int, int] | None" = None,
) -> "str | None":
    """Remove ``name`` in ``root/parent_parts`` when it is still the judged
    entry: a regular file (``directory=False``) or a directory, not a link, with
    ``identity``; and, when ``parent_identity`` is given, inside the judged
    parent. Returns ``None`` once removed, else the cause class of the skip.
    The unlink or rmdir's own ``OSError`` propagates to the caller."""

    wanted = stat.S_ISDIR if directory else stat.S_ISREG
    if _descriptor_removal():
        try:
            fd = contained_files.open_contained_dir(root, parent_parts)
        except OSError as exc:
            return _failure_class(exc)
        try:
            if parent_identity is not None and _identity(os.fstat(fd)) != parent_identity:
                return _CAUSE_ENTRY_CHANGED
            try:
                entry = os.stat(name, dir_fd=fd, follow_symlinks=False)
            except OSError as exc:
                return _failure_class(exc)
            if not wanted(entry.st_mode) or _identity(entry) != identity:
                return _CAUSE_ENTRY_CHANGED
            if directory:
                os.rmdir(name, dir_fd=fd)
            else:
                os.unlink(name, dir_fd=fd)
        finally:
            os.close(fd)
        return None
    # Windows: by path, immediately before the removal (the documented window).
    try:
        contained_files.open_contained_dir(root, parent_parts)
    except OSError as exc:
        return _failure_class(exc)
    parent = Path(root).joinpath(*parent_parts)
    path = parent / name
    try:
        if parent_identity is not None:
            parent_info = os.lstat(parent)
            if _is_link_or_reparse(parent, parent_info) or _identity(parent_info) != parent_identity:
                return _CAUSE_ENTRY_CHANGED
        entry = os.lstat(path)
    except OSError as exc:
        return _failure_class(exc)
    if _is_link_or_reparse(path, entry) or not wanted(entry.st_mode) or _identity(entry) != identity:
        return _CAUSE_ENTRY_CHANGED
    if directory:
        os.rmdir(path)
    else:
        os.unlink(path)
    return None


def _judge_stale_skill_paths(
    root: Path, stale_paths: "tuple[str, ...]"
) -> "list[tuple[str, tuple[int, int] | None, tuple[int, int] | None]]":
    """``(rel, file identity, folder identity)`` for every present stale skill
    path (wave 200ey, change 200eu), judged by ``lstat``: a regular file's
    identity, or ``None`` for a link or reparse point, which the removal skips
    with a NOTICE; and the identity of its folder (``None`` when that is a link
    or not a directory). Absent paths and other entry kinds (a directory) are
    not listed, as before."""

    judged: "list[tuple[str, tuple[int, int] | None, tuple[int, int] | None]]" = []
    for rel in stale_paths:
        stale = root / rel
        try:
            info = os.lstat(stale)
        except OSError:
            continue
        folder_id: "tuple[int, int] | None" = None
        try:
            folder_info = os.lstat(stale.parent)
        except OSError:
            folder_info = None
        if (
            folder_info is not None
            and stat.S_ISDIR(folder_info.st_mode)
            and not _is_link_or_reparse(stale.parent, folder_info)
        ):
            folder_id = _identity(folder_info)
        if _is_link_or_reparse(stale, info):
            judged.append((rel, None, folder_id))
        elif stat.S_ISREG(info.st_mode):
            judged.append((rel, _identity(info), folder_id))
    return judged


def _removal_skipped_notice(what: str, rel: str, cause: str) -> None:
    print(
        f"render_agent_surfaces: NOTICE - {what} left in place: {_display_name(rel)} "
        f"was not removed ({cause}); remove it by hand if it is no longer wanted",
        file=sys.stderr,
    )


def render_skills(repo_root: Path, *, skip_paths: "frozenset[str]" = frozenset()) -> list[str]:
    """Render every registry skill, then every declared skill, to each active skill host.

    Returns changed paths only (write_text compares bytes first). Runs on
    every render — per-skill doc-presence gates (requires_doc) decide skill
    eligibility; host-dir presence decides where each eligible skill lands.
    Also removes the pre-registry stale paths so migrated skills never
    coexist with their old locations. A declared prompt doc in ``skip_paths``
    (see :func:`unrecorded_profile_prompt_paths`) is not created this render.
    """

    for skill in SKILL_REGISTRY:
        if not _SKILL_NAME_PATTERN.fullmatch(skill.name):
            raise RuntimeError(
                f"skill name violates the wf- kebab-case policy: {skill.name!r}"
            )
    # Re-check the declared skills before this pass's own writes (wave 1zv8c).
    skills = _all_skills()
    root = repo_root.resolve()
    active_skill_roots: dict[str, Path] = {}
    for host_root, skills_dir in SKILL_HOSTS:
        if not (root / host_root).is_dir():
            continue
        declared_root = root / skills_dir
        try:
            resolved_root = declared_root.resolve(strict=False)
        except OSError as exc:
            raise RuntimeError(
                "declared host skill root cannot be resolved safely: "
                f"{_display_name(skills_dir)} ({type(exc).__name__})"
            ) from exc
        if (
            _skill_path_has_symlink_component(root, declared_root)
            or resolved_root != declared_root
        ):
            raise RuntimeError(
                "declared host skill root contains a symlink: " f"{skills_dir}"
            )
        active_skill_roots[skills_dir] = declared_root

    # Validate every cleanup and write destination before mutating any host.
    # This preserves all hosts if one later lexical path redirects through a
    # symlink, including a per-skill directory symlink inside a valid root.
    stale_paths = stale_skill_paths()
    for rel in stale_paths:
        stale = root / rel
        if _skill_path_has_symlink_component(root, stale):
            raise RuntimeError(
                "stale skill path escapes its declared host skill root through a symlink: "
                f"{rel}"
            )
    creations = {
        prompt_doc: template
        for prompt_doc, template in _declared_prompt_doc_creations(root).items()
        if prompt_doc not in skip_paths
    }
    creation_paths = {
        prompt_doc: _contained_review_carrier_path(root, prompt_doc) for prompt_doc in creations
    }
    for skill in skills:
        if not _skill_is_eligible(root, skill, creations):
            continue
        for skills_dir, declared_root in active_skill_roots.items():
            target = declared_root / skill.name / "SKILL.md"
            if _skill_path_has_symlink_component(root, target):
                raise RuntimeError(
                    "skill output path escapes its declared host skill root through a symlink: "
                    f"{skills_dir}/{skill.name}/SKILL.md"
                )
    # Wave 1zyb3 (change 1zxnu): decide every declared-skill refusal and every
    # orphan before the first write.
    refused = _refused_declared_skill_paths(root, skills, creations, active_skill_roots)
    orphans = _declared_skill_orphans(active_skill_roots)
    # Wave 200ey (200eu): each present stale path is judged (and its identity
    # recorded) before the first removal too.
    stale_judged = {
        rel: (file_id, folder_id)
        for rel, file_id, folder_id in _judge_stale_skill_paths(root, stale_paths)
    }

    written: list[str] = []
    for rel in stale_paths:
        stale = root / rel
        skills_dir = next(
            (
                declared_skills_dir
                for _host_root, declared_skills_dir in SKILL_HOSTS
                if rel == declared_skills_dir or rel.startswith(f"{declared_skills_dir}/")
            ),
            None,
        )
        if skills_dir is None:
            raise RuntimeError(f"stale skill path has no declared host skill root: {rel}")
        try:
            declared_root = (root / skills_dir).resolve(strict=False)
            resolved_parent = stale.parent.resolve(strict=False)
        except OSError as exc:
            raise RuntimeError(
                "stale skill path cannot be resolved safely: "
                f"{_display_name(rel)} ({type(exc).__name__})"
            ) from exc
        if not declared_root.is_relative_to(root) or not resolved_parent.is_relative_to(
            declared_root
        ):
            raise RuntimeError(
                "stale skill path escapes its declared host skill root through a symlink: "
                f"{_display_name(rel)}"
            )
        if rel not in stale_judged:
            continue
        file_id, folder_id = stale_judged[rel]
        if file_id is None:
            _removal_skipped_notice("stale skill path", rel, "the entry is a link")
            continue
        parent_parts = Path(rel).parent.parts
        try:
            cause = _remove_judged_entry(
                root, parent_parts, Path(rel).name, file_id,
                directory=False, parent_identity=folder_id,
            )
        except OSError as exc:
            raise RuntimeError(
                f"cannot remove the stale skill path {_display_name(rel)} ({type(exc).__name__})"
            ) from exc
        if cause is not None:
            _removal_skipped_notice("stale skill path", rel, cause)
            continue
        written.append(rel)
        # Remove the emptied per-skill directory (never the shared skills/
        # root, which other skills may populate), relative to the host skill
        # root and only while it is still the folder judged.
        if parent_parts[-1] != "skills" and folder_id is not None:
            try:
                cause = _remove_judged_entry(
                    root, parent_parts[:-1], parent_parts[-1], folder_id, directory=True
                )
            except OSError:
                cause = None
            if cause is not None:
                _removal_skipped_notice("stale skill folder", "/".join(parent_parts), cause)
    for orphan in orphans:
        rel = orphan.rel
        folder_rel = rel.rsplit("/", 1)[0]
        folder_parts = tuple(folder_rel.split("/"))
        try:
            cause = _remove_judged_entry(
                root, folder_parts, "SKILL.md", orphan.file_id,
                directory=False, parent_identity=orphan.folder_id,
            )
        except OSError as exc:
            # Wave 200xy (200v2): relative path and exception class only,
            # like the rmdir NOTICE below; the OSError text names the
            # absolute file path.
            raise RuntimeError(
                f"cannot remove the undeclared skill {_display_name(rel)} ({type(exc).__name__})"
            ) from exc
        if cause is not None:
            # Wave 200ey (200eu): the folder or SKILL.md is no longer the
            # entry judged, so neither is removed.
            _removal_skipped_notice("undeclared skill", rel, cause)
            continue
        written.append(rel)
        # unlink + rmdir, never rmtree: an entry that appeared in the folder
        # after the orphan decision survives, and the folder is reported.
        try:
            cause = _remove_judged_entry(
                root, folder_parts[:-1], folder_parts[-1], orphan.folder_id, directory=True
            )
        except OSError as exc:
            print(
                "render_agent_surfaces: NOTICE - undeclared skill folder left in place: "
                f"{_display_name(folder_rel)} could not be removed after its marked SKILL.md "
                f"was ({type(exc).__name__}); remove the folder by hand if it is no longer wanted",
                file=sys.stderr,
            )
            continue
        if cause is not None:
            _removal_skipped_notice("undeclared skill folder", folder_rel, cause)
    if creations:
        today = time.strftime("%Y-%m-%d")
        for prompt_doc, template in creations.items():
            content = _framework_read_text(template).replace("{{generated_at}}", today)
            _write_review_carrier_text(creation_paths[prompt_doc], content, exclusive=True, root=root)
            written.append(prompt_doc)
    for rel in refused:
        print(
            "render_agent_surfaces: NOTICE - declared skill not rendered: "
            f"{rel} exists without the declared-skill marker, so it is not overwritten; "
            "rename the declared skill, or remove or rename the hand-written folder",
            file=sys.stderr,
        )
    for skill in skills:
        if skill.requires_doc and not (root / skill.requires_doc).is_file():
            continue
        for host_root, skills_dir in SKILL_HOSTS:
            if skills_dir not in active_skill_roots:
                continue
            rel = f"{skills_dir}/{skill.name}/SKILL.md"
            if rel in refused:
                continue
            target = root / rel
            document = skill_document(skill)
            # A skill file can also be a review carrier (wf-guru on Codex):
            # the reconcile passes own marked regions inside it. Graft any
            # existing well-formed regions into the fresh template with the
            # SAME upsert functions the reconcilers use, so a re-render is
            # byte-identical and the changed-only manifest stays quiet.
            if target.is_file():
                try:
                    existing = _read_repo_text(root, target)
                except OSError:
                    existing = ""
                protocol_block = _extract_marked_block(
                    existing, REVIEW_PROTOCOL_MARKER_BEGIN, REVIEW_PROTOCOL_MARKER_END
                )
                if protocol_block is not None:
                    document = (
                        _upsert_review_protocol_region(document, protocol_block)
                        or document
                    )
                policy_block = _extract_marked_block(
                    existing,
                    REVIEW_POLICY_SURFACE_MARKER_BEGIN,
                    REVIEW_POLICY_SURFACE_MARKER_END,
                )
                if policy_block is not None:
                    document = (
                        _upsert_review_policy_region(document, policy_block)
                        or document
                    )
            if write_text(target, document, root=root):
                written.append(rel)
    return written

