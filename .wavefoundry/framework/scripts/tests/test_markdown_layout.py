"""Change 22y1k: a heading has an empty line above it.

``markdown_layout.ensure_blank_line_before_headings`` inserts the missing line and
``headings_without_blank_line`` reports where one is missing.
"""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parents[1]
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

import markdown_layout as subject  # noqa: E402

fix = subject.ensure_blank_line_before_headings


class InsertionTests(unittest.TestCase):
    def assert_inserted(self, previous: str) -> None:
        text = f"# Title\n\n{previous}\n## Next\n\nbody\n"
        self.assertEqual(fix(text), f"# Title\n\n{previous}\n\n## Next\n\nbody\n", previous)

    def test_a_line_is_inserted_after_each_kind_of_non_blank_line(self) -> None:
        for previous in (
            "- a list item",
            "| a | table row |",
            "A sentence of prose.",
            "<!-- wave:exploration-avoided end -->",
            "<!-- x:end -->",
            "<!-- we begin here -->",
            "<!-- x begin -->",
            "<!-- a plain comment -->",
        ):
            with self.subTest(previous=previous):
                self.assert_inserted(previous)

    def test_every_heading_level_and_indent_up_to_three_spaces_is_a_heading(self) -> None:
        for heading in ("# a", "###### a", "   ## a", "##\ta", "##"):
            with self.subTest(heading=heading):
                self.assertEqual(fix(f"text\n{heading}\n"), f"text\n\n{heading}\n")

    def test_lines_that_are_not_headings_are_left_alone(self) -> None:
        for line in ("#tag", "####### seven", "    ## four spaces", "\\## escaped", "a ## b"):
            with self.subTest(line=line):
                text = f"text\n{line}\n"
                self.assertEqual(fix(text), text)
                self.assertEqual(subject.headings_without_blank_line(text), [])


class ExemptionTests(unittest.TestCase):
    def assert_unchanged(self, text: str) -> None:
        self.assertEqual(fix(text), text)
        self.assertEqual(subject.headings_without_blank_line(text), [])

    def test_a_heading_on_the_first_line(self) -> None:
        self.assert_unchanged("## First\ntext\n")

    def test_a_heading_inside_a_closed_fence(self) -> None:
        self.assert_unchanged("text\n\n```\ncode\n## not a heading\n```\n")
        self.assert_unchanged("text\n\n~~~md\nline\n# also not\n~~~\n")

    def test_an_unterminated_fence_does_not_suppress_the_fix(self) -> None:
        self.assertEqual(fix("text\n\n```\ncode\n## Heading\n"), "text\n\n```\ncode\n\n## Heading\n")

    def test_a_heading_after_a_renderer_begin_marker(self) -> None:
        for marker in (
            "<!-- x:begin -->",
            "<!-- x:y begin -->",
            "<!-- wavefoundry:review-policy:begin -->",
            "<!-- wave:executable-review-evidence begin — generated by a renderer; do not edit -->",
            "  <!-- wave:root-bridge begin -->",
        ):
            with self.subTest(marker=marker):
                self.assert_unchanged(f"text\n\n{marker}\n## Generated\n")

    def test_a_begin_marker_is_matched_only_at_the_start_of_the_previous_line(self) -> None:
        text = "see <!-- x:begin --> here\n## Heading\n"
        self.assertEqual(fix(text), "see <!-- x:begin --> here\n\n## Heading\n")

    def test_a_heading_after_a_blank_or_whitespace_only_line(self) -> None:
        self.assert_unchanged("text\n\n## Heading\n")
        self.assert_unchanged("text\n \t \n## Heading\n")

    def test_a_blockquoted_heading_is_left_unchanged_and_reported_only_on_request(self) -> None:
        text = "text\n\n> quoted\n> ## Quoted heading\n"
        self.assertEqual(fix(text), text)
        self.assertEqual(subject.headings_without_blank_line(text), [])
        self.assertEqual(subject.headings_without_blank_line(text, include_blockquoted=True), [3])
        spaced = "> quoted\n>\n> ## Quoted heading\n"
        self.assertEqual(subject.headings_without_blank_line(spaced, include_blockquoted=True), [])


class FidelityTests(unittest.TestCase):
    DOC = "# Title\n\n- item\n## One\ntext\n### Two\n\n| a |\n## Three\n"

    def test_nothing_else_changes(self) -> None:
        fixed = fix(self.DOC)
        self.assertEqual(fixed, "# Title\n\n- item\n\n## One\ntext\n\n### Two\n\n| a |\n\n## Three\n")
        self.assertEqual([line for line in fixed.split("\n") if line], [line for line in self.DOC.split("\n") if line])
        self.assertEqual(subject.headings_without_blank_line(self.DOC), [3, 5, 8])

    def test_applying_it_twice_equals_applying_it_once(self) -> None:
        once = fix(self.DOC)
        self.assertEqual(fix(once), once)
        self.assertEqual(subject.headings_without_blank_line(once), [])

    def test_a_crlf_document_stays_crlf(self) -> None:
        crlf = self.DOC.replace("\n", "\r\n")
        fixed = fix(crlf)
        self.assertEqual(fixed, fix(self.DOC).replace("\n", "\r\n"))
        self.assertNotIn("\n", fixed.replace("\r\n", ""))
        self.assertEqual(fix(fixed), fixed)

    def test_a_document_with_no_final_newline_keeps_none(self) -> None:
        self.assertEqual(fix("text\n## End"), "text\n\n## End")
        self.assertEqual(fix("text\r\n## End"), "text\r\n\r\n## End")
        self.assertEqual(fix(""), "")
        self.assertEqual(fix("no headings\r"), "no headings\r")

    def test_a_clean_document_is_returned_unchanged(self) -> None:
        clean = fix(self.DOC)
        self.assertIs(fix(clean), clean)


if __name__ == "__main__":
    unittest.main()
