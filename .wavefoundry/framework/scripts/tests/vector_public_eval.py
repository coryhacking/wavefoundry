"""Development-only four-lane public retrieval experiment; never production certification.

Uses an isolated current Lance/registry snapshot for canonical health/epoch checks.
SQLite replaces only the dense search operation, retaining public retrieval policy.
Each lane has one exclusive output directory; failures retain an attempt receipt.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import sqlite3
import sys
import time
import traceback


class VerifiedQuery:
    """Observe materialization even when the production caller suppresses errors."""
    def __init__(self, query, proof):
        self.query, self.proof = query, proof

    def __getattr__(self, name):
        def call(*args, **kwargs):
            result = getattr(self.query, name)(*args, **kwargs)
            if name == 'to_list':
                self.proof['materialized'] = True
                return result
            return VerifiedQuery(result, self.proof)
        return call


class VerifiedTable:
    def __init__(self, table, proof, exact=False):
        self.table, self.proof, self.exact = table, proof, exact

    def search(self, vector):
        query = self.table.search(vector)
        if self.exact:
            query = query.bypass_vector_index()
            self.proof['bypass_applied'] = True
        return VerifiedQuery(query, self.proof)


class ScalarStore:
    def __init__(self, path, tables):
        import sqlite_vec
        import numpy as np
        self.db = sqlite3.connect(path, check_same_thread=False)
        self.db.enable_load_extension(True)
        sqlite_vec.load(self.db)
        self.db.enable_load_extension(False)
        self.db.execute('PRAGMA case_sensitive_like=ON')
        self.counts = {}
        for name, table in tables.items():
            if name not in ('docs', 'code'):
                raise ValueError(name)
            self.db.execute(f'CREATE TABLE {name}(rid INTEGER PRIMARY KEY, vector BLOB, kind TEXT, language TEXT, tags TEXT, payload TEXT)')
            count = 0
            for batch in table.to_arrow().to_batches(max_chunksize=512):
                values = []
                for row in batch.to_pylist():
                    vector = np.asarray(row.pop('vector'), dtype='<f4').tobytes()
                    values.append((vector, row.get('kind', ''), row.get('language', ''), row.get('tags', ''), json.dumps(row)))
                self.db.executemany(f'INSERT INTO {name}(vector,kind,language,tags,payload) VALUES(?,?,?,?,?)', values)
                count += len(values)
            self.counts[name] = count
        self.db.commit()

    def search(self, name, vector, limit, where):
        import numpy as np
        if name not in ('docs', 'code'):
            raise ValueError(name)
        # Predicate is generated by unchanged production code, not user SQL.
        predicate = where or '1'
        rows = self.db.execute(
            f'SELECT payload,vec_distance_cosine(vector,?) AS distance FROM {name} WHERE {predicate} ORDER BY distance,rid LIMIT ?',
            (np.asarray(vector, dtype='<f4').tobytes(), limit)).fetchall()
        return [dict(json.loads(payload), score=1.0-distance) for payload, distance in rows]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--lane', choices=('baseline', 'latest-ann', 'latest-exact', 'sqlite-scalar'), required=True)
    parser.add_argument('--shared-site', type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    os.environ['HF_HUB_OFFLINE'] = '1'
    os.environ['TRANSFORMERS_OFFLINE'] = '1'
    if args.shared_site:
        sys.path.append(str(args.shared_site))
    scripts = args.root / '.wavefoundry/framework/scripts'
    sys.path.insert(0, str(scripts))
    import retrieval_eval as evaluation
    import server_impl as server
    import lancedb
    expected = '0.33.0' if args.lane == 'baseline' else '0.38.0'
    if lancedb.__version__ != expected:
        raise RuntimeError(f'Expected LanceDB {expected}, got {lancedb.__version__}')
    trace = []
    attempt = {'kind': 'experimental_public_path_overlay', 'lane': args.lane,
               'production_certification': False, 'root': str(args.root.resolve()),
               'driver_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
               'packages': {p: importlib.metadata.version(p) for p in ('lancedb', 'numpy', 'pyarrow', 'fastembed')},
               'lancedb_module': lancedb.__file__}
    (args.output / 'attempt.json').write_text(json.dumps(attempt, indent=2))
    original_factory = evaluation._new_evaluation_index
    original_call = evaluation._call_public_path
    original_fts = server._fts_probed_fetch
    scalar = None
    try:
        if args.lane == 'sqlite-scalar':
            connection = lancedb.connect(args.root / '.wavefoundry/index')
            scalar = ScalarStore(args.output / 'vectors.sqlite', {n: connection.open_table(n) for n in ('docs', 'code')})
            attempt['sqlite_counts'] = scalar.counts
            attempt['packages']['sqlite-vec'] = importlib.metadata.version('sqlite-vec')

        def factory(module, root):
            index = original_factory(module, root)
            for method in ('_embed_query', '_rerank', '_agent_rerank'):
                original = getattr(index, method)
                def measured(*a, _method=method, _original=original, **kw):
                    start = time.perf_counter()
                    try:
                        return _original(*a, **kw)
                    finally:
                        trace.append({'phase': _method, 'ms': (time.perf_counter()-start)*1000})
                setattr(index, method, measured)
            original_dense = index._lance_search

            def dense(table, query_vec, top_n, where=None, layer='project'):
                start = time.perf_counter()
                entry = {'phase': 'dense_hydrated', 'backend': args.lane, 'table': table.name,
                         'limit': top_n, 'where': where, 'layer': layer}
                try:
                    if scalar is not None:
                        rows = scalar.search(table.name, query_vec, top_n, where)
                        for row in rows:
                            row['path'] = index._qualify_index_path(row.get('path', ''), layer)
                    else:
                        proof = {}
                        rows = original_dense(VerifiedTable(table, proof, args.lane == 'latest-exact'), query_vec, top_n, where, layer)
                        if proof.get('materialized') is not True:
                            raise RuntimeError('Dense substrate failed without successful materialization')
                        entry['proof'] = proof
                    entry['returned'] = len(rows)
                    return rows
                except Exception as exc:
                    entry['error'] = repr(exc)
                    raise
                finally:
                    entry['ms'] = (time.perf_counter()-start)*1000
                    trace.append(entry)
            index._lance_search = dense
            return index

        def public_call(module, index, root, tool, query, epoch):
            offset = len(trace)
            start = time.perf_counter()
            response = original_call(module, index, root, tool, query, epoch)
            events = trace[offset:]
            record = {'tool': tool, 'query': query, 'root': str(root),
                      'total_ms': (time.perf_counter()-start)*1000,
                      'status': response.get('status'), 'events': list(events)}
            data = response.get('data') or {}
            record['search_mode'] = data.get('search_mode')
            record['reranked'] = data.get('reranked')
            with (args.output / 'calls.jsonl').open('a') as stream:
                stream.write(json.dumps(record)+'\n')
            print(f'{args.lane} {tool} {record["total_ms"]:.0f}ms dense={sum(e["phase"] == "dense_hydrated" for e in events)}', flush=True)
            return response

        def fts(*a, **kw):
            start = time.perf_counter()
            try:
                return original_fts(*a, **kw)
            finally:
                trace.append({'phase': 'lexical_fetch', 'ms': (time.perf_counter()-start)*1000})

        evaluation._new_evaluation_index = factory
        evaluation._call_public_path = public_call
        server._fts_probed_fetch = fts
        report = evaluation.run_evaluation(args.root, args.root / 'docs/evals/retrieval-quality-golden.json')
        attempt['report'] = report
        attempt['status'] = 'completed'
    except BaseException:
        attempt['status'] = 'invalid'
        attempt['error'] = traceback.format_exc()
        raise
    finally:
        evaluation._new_evaluation_index = original_factory
        evaluation._call_public_path = original_call
        server._fts_probed_fetch = original_fts
        if scalar is not None:
            scalar.db.close()
        (args.output / 'result.json').write_text(json.dumps(attempt, indent=2)+'\n')


if __name__ == '__main__':
    main()
